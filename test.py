def infer_service(sport: int, dport: int, protocol: str) -> str:
    if protocol == "icmp":
        return "icmp"
    for port in [dport, sport]:
        if port in SERVICE_MAP:
            return SERVICE_MAP[port]
    return "-"


def update_tcp_flags(record: FlowRecord, flags: int, is_forward: bool) -> None:
    if flags & TCP_SYN and not (flags & TCP_ACK):
        record._saw_syn = True
    if flags & TCP_SYN and flags & TCP_ACK:
        record._saw_synack = True
    if flags & TCP_RST:
        record._saw_rst = True
        record._rst_from_orig = is_forward
    if flags & TCP_FIN:
        if is_forward:
            record._saw_fin_orig = True
        else:
            record._saw_fin_resp = True
    if (flags & TCP_PSH or flags & TCP_ACK) and not (flags & TCP_SYN):
        record._saw_data = True


