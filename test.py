"""
flow_parser.py — Network Traffic Flow Aggregator using TShark
--------------------------------------------------------------
Processes .pcap files or live captures into bidirectional flow-level records.
Streams packets via TShark subprocess — never loads entire pcap into memory.

Flows are sent in real-time to a remote HTTP API endpoint via POST requests.
The script is designed to run as a persistent background service (systemd).

Output fields match the schema shown below (Zeek/CTU-13 inspired):
    src_ip, dst_ip, src_port, dst_port, proto, service, conn_state,
    duration, src_bytes, dst_bytes, missed_bytes,
    src_pkts, src_ip_bytes, dst_pkts, dst_ip_bytes,
    dns_qclass, dns_qtype, dns_rcode,<
    http_trans_depth, http_request_body_len, http_response_body_len,
    http_status_code, raw_log

Usage:
    # From pcap file → send to API
    python flow_parser.py -f capture.pcap --server http://0.0.0.0:8000/analyse

    # Live capture → send to API with 2-min idle timeout + local JSON backup
    python flow_parser.py -i eth0 --server http://192.168.1.100:8000/analyse --timeout 120 -o flows.json

    # Live capture → default API endpoint
    python flow_parser.py -i eth0

    # Run as daemon (background process, survives terminal close)
    python flow_parser.py -i eth0 --daemon

Author: Generated by Claude
"""

