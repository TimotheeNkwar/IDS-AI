def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Parse network traffic into flow-level records and stream to an HTTP API.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Read pcap and POST flows to API
  python flow_parser.py -f capture.pcap

  # Live capture with custom server
  python flow_parser.py -i eth0 --server http://192.168.1.100:8000/analyse

  # Live capture as background daemon
  python flow_parser.py -i eth0 --daemon

  # Stop running daemon
  python flow_parser.py --stop

  # Install as systemd service (run as root)
  python flow_parser.py -i eth0 --install-service
        """
    )

    src = p.add_mutually_exclusive_group()
    src.add_argument("-f", "--file",      metavar="PCAP",  help="Input .pcap / .pcapng file")
    src.add_argument("-i", "--interface", metavar="IFACE", help="Live capture interface (e.g. eth0)")

