def derive_conn_state(
    saw_syn: bool,
    saw_synack: bool,
    saw_fin_orig: bool,
    saw_fin_resp: bool,
    saw_rst: bool,
    saw_data: bool,
    rst_from_orig: bool,
    protocol: str,
) -> str:
    if protocol != "tcp":
        return "-"
    if saw_rst:
        if not saw_synack:
            return "RSTOS0" if rst_from_orig else "REJ"
        return "RSTO" if rst_from_orig else "RSTR"
    if saw_syn and not saw_synack:
        return "S0"
    if saw_syn and saw_synack and not saw_data and not saw_fin_orig and not saw_fin_resp:
        return "S1"
    if saw_synack and saw_fin_orig and not saw_fin_resp:
        return "S2"
    if saw_synack and saw_fin_resp and not saw_fin_orig:
        return "S3"
    if saw_synack and saw_fin_orig and saw_fin_resp:
        return "SF"
    if not saw_syn and saw_data:
        return "OTH"
    return "OTH"


