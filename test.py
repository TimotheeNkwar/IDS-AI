def build_tshark_command(
    source: str,
    is_interface: bool = False,
    capture_filter: str = "",
    display_filter: str = "ip",
) -> List[str]:
    cmd = ["tshark"]
    if is_interface:
        cmd += ["-i", source]
        if capture_filter:
            cmd += ["-f", capture_filter]
    else:
        cmd += ["-r", source]
    if display_filter:
        cmd += ["-Y", display_filter]
    cmd += ["-T", "fields"]
    for f in TSHARK_FIELDS:
        cmd += ["-e", f]
    cmd += [
        "-E", f"separator={TSHARK_SEPARATOR}",
        "-E", "header=n",
        "-E", "occurrence=f",
        "-q",
    ]
    return cmd


def _int(val: str, default: int = 0) -> int:
    try:
        return int(val) if val else default
    except ValueError:
        return default


def parse_packet_line(line: str) -> Optional[dict]:
    parts = line.rstrip("\n").split(TSHARK_SEPARATOR)
    if len(parts) < len(TSHARK_FIELDS):
        return None

    (ts, ip_src, ip_dst,
     tcp_sport, tcp_dport,
     udp_sport, udp_dport,
     ip_proto, frame_len,
     tcp_flags_hex, ip_len,
     dns_qclass, dns_qtype, dns_rcode,
     http_req_ver, http_content_len, http_resp_num,
     http_status) = parts[:18]

    if not ip_src or not ip_dst:
        return None

    try:
        timestamp = float(ts)
        proto_num = _int(ip_proto)
        length    = _int(frame_len)
        ip_length = _int(ip_len)
    except ValueError:
        return None

    if proto_num == 6:
        protocol = "tcp"
        sport = _int(tcp_sport)
        dport = _int(tcp_dport)
    elif proto_num == 17:
        protocol = "udp"
        sport = _int(udp_sport)
        dport = _int(udp_dport)
    elif proto_num == 1:
        protocol = "icmp"
        sport = 0
        dport = 0
    else:
        protocol = f"proto{proto_num}"
        sport = 0
        dport = 0

    tcp_flags = 0
    if tcp_flags_hex:
        try:
            tcp_flags = int(tcp_flags_hex, 16)
        except ValueError:
            pass

    return {
        "timestamp":      timestamp,
        "ip_src":         ip_src,
        "ip_dst":         ip_dst,
        "sport":          sport,
        "dport":          dport,
        "protocol":       protocol,
        "frame_len":      length,
        "ip_len":         ip_length,
        "tcp_flags":      tcp_flags,
        "dns_qclass":     _int(dns_qclass),
        "dns_qtype":      _int(dns_qtype),
        "dns_rcode":      _int(dns_rcode),
        "http_req":       bool(http_req_ver),
        "http_req_body":  _int(http_content_len) if http_req_ver else 0,
        "http_resp_body": _int(http_content_len) if http_resp_num else 0,
        "http_status":    _int(http_status),
    }


def stream_packets(tshark_cmd: List[str]) -> Iterator[dict]:
    try:
        proc = subprocess.Popen(
            tshark_cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
        )
    except FileNotFoundError:
        print("ERROR: tshark not found. Install Wireshark/TShark first.", file=sys.stderr)
        sys.exit(1)

    try:
        for line in proc.stdout:
            pkt = parse_packet_line(line)
            if pkt:
                yield pkt
    finally:
        proc.stdout.close()
        proc.wait()
        if proc.returncode not in (0, None, -2):
            err = proc.stderr.read()
            if err:
                print(f"TShark stderr: {err[:500]}", file=sys.stderr)


