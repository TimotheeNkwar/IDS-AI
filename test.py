def write_json(flows: List[FlowRecord], path: str) -> None:
    records = [f.to_dict() for f in flows]
    with open(path, "w") as fh:
        json.dump(records, fh, indent=2)
    print(f"[+] Wrote {len(records)} flows → {path}")


def write_csv(flows: List[FlowRecord], path: str) -> None:
    with open(path, "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=CSV_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for f in flows:
            writer.writerow(f.to_dict())
    print(f"[+] Wrote {len(flows)} flows → {path}")


