def make_flow_key(
    ip_src: str, ip_dst: str,
    sport: int, dport: int,
    protocol: str,
) -> Tuple[FlowKey, bool]:
    a = (ip_src, sport)
    b = (ip_dst, dport)
    if a <= b:
        return (ip_src, ip_dst, sport, dport, protocol), True
    else:
        return (ip_dst, ip_src, dport, sport, protocol), False


class FlowTable:
    def __init__(self, idle_timeout: float = 0):
        self.flows:         Dict[FlowKey, FlowRecord] = {}
        self.idle_timeout:  float = idle_timeout
        self._last_cleanup: float = 0

    def process_packet(self, pkt: dict) -> List[FlowRecord]:
        key, is_forward = make_flow_key(
            pkt["ip_src"], pkt["ip_dst"],
            pkt["sport"],  pkt["dport"],
            pkt["protocol"],
        )
        ts        = pkt["timestamp"]
        frame_len = pkt["frame_len"]
        ip_len    = pkt["ip_len"]

        if key not in self.flows:
            ip_a, ip_b, port_a, port_b, proto = key
            self.flows[key] = FlowRecord(
                src_ip     = ip_a,
                dst_ip     = ip_b,
                src_port   = port_a,
                dst_port   = port_b,
                proto      = proto,
                service    = infer_service(port_a, port_b, proto),
                first_seen = ts,
                last_seen  = ts,
            )

        rec = self.flows[key]
        rec.last_seen = max(rec.last_seen, ts)

        if is_forward:
            rec.src_pkts     += 1
            rec.src_bytes    += frame_len
            rec.src_ip_bytes += ip_len
        else:
            rec.dst_pkts     += 1
            rec.dst_bytes    += frame_len
            rec.dst_ip_bytes += ip_len

        if pkt["protocol"] == "tcp":
            update_tcp_flags(rec, pkt["tcp_flags"], is_forward)

        if pkt["dns_qclass"] and not rec.dns_qclass:
            rec.dns_qclass = pkt["dns_qclass"]
        if pkt["dns_qtype"] and not rec.dns_qtype:
            rec.dns_qtype = pkt["dns_qtype"]
        if pkt["dns_rcode"] and not rec.dns_rcode:
            rec.dns_rcode = pkt["dns_rcode"]

        if pkt["http_req"]:
            rec.http_trans_depth += 1
        if pkt["http_req_body"]:
            rec.http_request_body_len += pkt["http_req_body"]
        if pkt["http_resp_body"]:
            rec.http_response_body_len += pkt["http_resp_body"]
        if pkt["http_status"] and not rec.http_status_code:
            rec.http_status_code = pkt["http_status"]

        expired = []
        if self.idle_timeout > 0 and (ts - self._last_cleanup) > 10:
            self._last_cleanup = ts
            expired = list(self._expire_flows(ts))

        return expired

    def _expire_flows(self, current_ts: float) -> Iterator[FlowRecord]:
        expired_keys = [
            k for k, v in self.flows.items()
            if (current_ts - v.last_seen) >= self.idle_timeout
        ]
        for k in expired_keys:
            yield self.flows.pop(k)

    def all_flows(self) -> Iterator[FlowRecord]:
        yield from self.flows.values()


