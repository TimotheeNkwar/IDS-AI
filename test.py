class ApiSender:
    """
    Background thread that batches flows from a queue and POSTs them
    to the configured HTTP API endpoint as JSON arrays.

    Retries indefinitely on failure — flows are re-queued so no data
    is lost if the server is temporarily unreachable.
    """

    def __init__(self, endpoint: str):
        self.endpoint    = endpoint
        self.queue:      Queue = Queue(maxsize=MAX_QUEUE_SIZE)
        self._thread     = threading.Thread(
                               target=self._run, daemon=True, name="ApiSender"
                           )
        self._stop       = threading.Event()
        self._sent:      int = 0
        self._dropped:   int = 0
        self._errors:    int = 0

    def start(self) -> None:
        self._thread.start()
        print(f"[*] API sender started → {self.endpoint}")

    def stop(self) -> None:
        self._stop.set()
        self._thread.join(timeout=15)
        print(f"[*] API sender stopped. Sent: {self._sent} | "
              f"Dropped: {self._dropped} | Errors: {self._errors}")

    def send(self, flow: FlowRecord) -> None:
        try:
            self.queue.put_nowait(flow.to_dict())
        except Exception:
            self._dropped += 1

    def _post(self, batch: List[dict]) -> bool:
        """POST a batch of flow dicts to the API. Returns True on success."""
        payload = json.dumps(batch).encode("utf-8")
        req = urllib.request.Request(
            self.endpoint,
            data    = payload,
            headers = {
                "Content-Type": "application/json",
                "User-Agent":   "flow-parser/1.0",
            },
            method = "POST",
        )
        try:
            with urllib.request.urlopen(req, timeout=SEND_TIMEOUT) as resp:
                status = resp.getcode()
                if status in (200, 201, 202, 204):
                    self._sent += len(batch)
                    return True
                print(f"[!] API returned HTTP {status}", file=sys.stderr)
                self._errors += 1
                return False
        except urllib.error.URLError as e:
            print(f"[!] POST failed: {e.reason} — will retry in {RECONNECT_DELAY}s",
                  file=sys.stderr)
            self._errors += 1
            return False
        except Exception as e:
            print(f"[!] Unexpected send error: {e}", file=sys.stderr)
            self._errors += 1
            return False

    def _run(self) -> None:
        batch: List[dict] = []
        last_flush = time.time()

        while not self._stop.is_set():
            # Drain queue into batch
            try:
                item = self.queue.get(timeout=0.2)
                batch.append(item)
            except Empty:
                pass

            now = time.time()
            batch_ready = len(batch) >= BATCH_SIZE
            timeout_hit = batch and (now - last_flush) >= BATCH_TIMEOUT

            if batch and (batch_ready or timeout_hit):
                success = self._post(batch)
                if success:
                    batch = []
                    last_flush = now
                else:
                    # Re-queue the batch items for retry
                    for item in batch:
                        try:
                            self.queue.put_nowait(item)
                        except Exception:
                            self._dropped += 1
                    batch = []
                    self._stop.wait(timeout=RECONNECT_DELAY)

        # Drain remaining on shutdown
        if batch:
            self._post(batch)
        remaining = []
        while not self.queue.empty():
            try:
                remaining.append(self.queue.get_nowait())
            except Empty:
                break
        if remaining:
            self._post(remaining)


