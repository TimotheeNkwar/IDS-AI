def daemonize(log_file: str = "/tmp/flow_parser.log") -> None:
    """
    Fork into background. Redirects stdout/stderr to a log file.
    Writes PID to PID_FILE so the process can be stopped later.
    """
    # First fork
    try:
        pid = os.fork()
        if pid > 0:
            print(f"[*] Daemon started with PID {pid}. Logs → {log_file}")
            sys.exit(0)
    except OSError as e:
        print(f"Fork #1 failed: {e}", file=sys.stderr)
        sys.exit(1)

    os.setsid()

    # Second fork
    try:
        pid = os.fork()
        if pid > 0:
            sys.exit(0)
    except OSError as e:
        print(f"Fork #2 failed: {e}", file=sys.stderr)
        sys.exit(1)

    # Write PID
    with open(PID_FILE, "w") as f:
        f.write(str(os.getpid()))

    # Redirect stdin/stdout/stderr
    sys.stdout.flush()
    sys.stderr.flush()
    with open(os.devnull, "r") as devnull:
        os.dup2(devnull.fileno(), sys.stdin.fileno())
    log = open(log_file, "a")
    os.dup2(log.fileno(), sys.stdout.fileno())
    os.dup2(log.fileno(), sys.stderr.fileno())

    print(f"[*] Daemon process started at {time.strftime('%Y-%m-%d %H:%M:%S')}", flush=True)


def stop_daemon() -> None:
    """Stop a running daemon by PID file."""
    if not os.path.exists(PID_FILE):
        print("No PID file found — daemon may not be running.")
        return
    with open(PID_FILE) as f:
        pid = int(f.read().strip())
    try:
        os.kill(pid, signal.SIGTERM)
        print(f"[*] Sent SIGTERM to PID {pid}")
        os.remove(PID_FILE)
    except ProcessLookupError:
        print(f"Process {pid} not found — already stopped.")
        os.remove(PID_FILE)
    except PermissionError:
        print(f"Permission denied killing PID {pid}")


